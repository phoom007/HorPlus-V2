/**
 * Utility function to extract all placeholders in format [ระบุ...] from text
 */
export function extractPlaceholders(text?: string): string[] {
  if (!text) return [];
  const matches = text.match(/\[ระบุ[^\]]*\]/g);
  if (!matches) return [];
  return Array.from(new Set(matches));
}
